package com.example.myagent.ui.common

import androidx.compose.ui.unit.dp

/**
 * Единая геометрия круглой кнопки съёмки.
 *
 * Используется кнопкой съёмки на камере и кнопкой «use» в просмотрщике,
 * чтобы обе были одного размера и стояли строго по одним координатам:
 * центр = (ширина экрана / 2, низ экрана - BottomPadding - Size / 2).
 */
object ShutterUi {
    /** Внешний диаметр кнопки (обводка + кольцо). */
    val Size = 72.dp

    /** Толщина белой обводки. */
    val BorderWidth = 4.dp

    /** Диаметр внутреннего белого круга. */
    val InnerSize = 60.dp

    /** Отступ низа строки с кнопкой от края экрана. */
    val BottomPadding = 24.dp
}